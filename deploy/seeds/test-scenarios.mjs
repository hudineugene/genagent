const db = new DatabaseSync(process.argv[2] || process.env.DB_PATH);
db.exec("PRAGMA busy_timeout = 5000");
const ins = db.prepare(
  "INSERT INTO test_scenarios (id, agent_id, name, mode, turns, persona, max_turns, criteria, created_at) VALUES (?, ?, ?, 'script', ?, '', 4, ?, ?)",
);
let t = Date.now();
for (const [agentName, list] of Object.entries(SETS)) {
  const agent = db.prepare("SELECT id FROM agents WHERE name = ?").get(agentName);
  if (!agent) {
    console.log(`нет агента: ${agentName}`);
    continue;
  }
  const have = new Set(db.prepare("SELECT name FROM test_scenarios WHERE agent_id = ?").all(agent.id).map((r) => r.name));
  let added = 0;
  for (const [name, turns, criteria] of list) {
    if (have.has(name)) continue;
    ins.run(randomUUID(), agent.id, name, JSON.stringify(turns), JSON.stringify(criteria.map((text) => ({ text }))), t++);
    added++;
  }
  console.log(`${agentName}: добавлено ${added}, всего ${have.size + added}`);
}
